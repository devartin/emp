//! Build script (SPEC §9.13).
//!
//! 1. Reads the normative command list `ALL_COMMANDS` from `src/commands/mod.rs`.
//! 2. Regenerates `capabilities/main.json` (an `allow-<command>` permission per command plus the fixed core grants)
//!    and the command allowlist block inside `isolation/index.js`, writing only when the content changed.
//! 3. Runs `tauri_build` with an `AppManifest` restricted to exactly those commands, so any command missing from the
//!    list cannot be called from JavaScript.

use std::fs;
use std::path::Path;

const COMMANDS_FILE: &str = "src/commands/mod.rs";
const CAPABILITY_FILE: &str = "capabilities/main.json";
const ISOLATION_FILE: &str = "isolation/index.js";
const ISOLATION_BEGIN: &str =
    "/* BEGIN ALL_COMMANDS (generated by build.rs from src/commands/mod.rs) */";
const ISOLATION_END: &str = "/* END ALL_COMMANDS */";

/// Non-command permissions granted to the main window (SPEC §9.13). The updater is P1 and not compiled in.
const CORE_PERMISSIONS: &[&str] = &[
    "core:event:allow-listen",
    "core:event:allow-unlisten",
    "core:window:allow-minimize",
    "core:window:allow-toggle-maximize",
    "core:window:allow-close",
    "core:window:allow-start-dragging",
    "core:window:allow-set-title",
    "core:window:allow-is-maximized",
    "core:window:allow-show",
    "core:app:allow-version",
    "process:allow-restart",
];

/// Extracts the string literals of `pub const ALL_COMMANDS: &[&str] = &[ ... ];`, ignoring `//` comments.
fn parse_all_commands(source: &str) -> Result<Vec<String>, String> {
    let start = source
        .find("pub const ALL_COMMANDS")
        .ok_or("ALL_COMMANDS not found in src/commands/mod.rs")?;
    let rest = &source[start..];
    let open = rest.find("&[").ok_or("ALL_COMMANDS has no `&[`")?;
    let body_start = open + 2;
    let close = rest[body_start..]
        .find("];")
        .ok_or("ALL_COMMANDS is not terminated by `];`")?;
    let body = &rest[body_start..body_start + close];
    let mut out = Vec::new();
    for line in body.lines() {
        let code = line.split("//").next().unwrap_or("");
        let mut chars = code.split('"');
        // Every odd segment is a literal.
        let _ = chars.next();
        while let Some(lit) = chars.next() {
            if lit.is_empty()
                || !lit
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
            {
                return Err(format!("invalid command name in ALL_COMMANDS: {lit:?}"));
            }
            out.push(lit.to_owned());
            let _ = chars.next();
        }
    }
    let mut seen = std::collections::HashSet::new();
    for c in &out {
        if !seen.insert(c) {
            return Err(format!("duplicate command in ALL_COMMANDS: {c}"));
        }
    }
    if out.is_empty() {
        return Err("ALL_COMMANDS is empty".into());
    }
    Ok(out)
}

fn write_if_changed(path: &Path, content: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).unwrap_or_else(|e| panic!("create {}: {e}", dir.display()));
        }
        fs::write(path, content).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
    }
}

fn capability_json(commands: &[String]) -> String {
    let mut permissions: Vec<String> = CORE_PERMISSIONS.iter().map(|s| (*s).to_owned()).collect();
    permissions.extend(
        commands
            .iter()
            .map(|c| format!("allow-{}", c.replace('_', "-"))),
    );
    let value = serde_json::json!({
        "$schema": "../gen/schemas/desktop-schema.json",
        "identifier": "main",
        "description": "Main window: core window/event grants and every EMP command in ALL_COMMANDS (SPEC §9.13). Generated by build.rs — do not edit.",
        "local": true,
        "windows": ["main"],
        "permissions": permissions,
    });
    let mut s = serde_json::to_string_pretty(&value).unwrap_or_default();
    s.push('\n');
    s
}

fn isolation_with_commands(js: &str, commands: &[String]) -> Result<String, String> {
    let b = js
        .find(ISOLATION_BEGIN)
        .ok_or("isolation/index.js lacks the BEGIN ALL_COMMANDS marker")?;
    let e = js
        .find(ISOLATION_END)
        .ok_or("isolation/index.js lacks the END ALL_COMMANDS marker")?;
    if e < b {
        return Err("isolation/index.js markers are out of order".into());
    }
    let mut list = String::from(ISOLATION_BEGIN);
    list.push_str("\n  const ALL_COMMANDS = [\n");
    for c in commands {
        list.push_str("    '");
        list.push_str(c);
        list.push_str("',\n");
    }
    list.push_str("  ];\n  ");
    Ok(format!("{}{}{}", &js[..b], list, &js[e..]))
}

fn main() {
    println!("cargo:rerun-if-changed={COMMANDS_FILE}");
    println!("cargo:rerun-if-changed={ISOLATION_FILE}");
    println!("cargo:rerun-if-changed=isolation/index.html");
    println!("cargo:rerun-if-env-changed=GITHUB_SHA");

    let commit: String = std::env::var("GITHUB_SHA")
        .ok()
        .filter(|s| s.bytes().all(|b| b.is_ascii_hexdigit()) && !s.is_empty())
        .map(|s| s.chars().take(12).collect())
        .unwrap_or_else(|| "dev".into());
    println!("cargo:rustc-env=EMP_COMMIT={commit}");

    let source =
        fs::read_to_string(COMMANDS_FILE).unwrap_or_else(|e| panic!("read {COMMANDS_FILE}: {e}"));
    let commands = parse_all_commands(&source).unwrap_or_else(|e| panic!("{e}"));

    write_if_changed(Path::new(CAPABILITY_FILE), &capability_json(&commands));

    let js =
        fs::read_to_string(ISOLATION_FILE).unwrap_or_else(|e| panic!("read {ISOLATION_FILE}: {e}"));
    let updated = isolation_with_commands(&js, &commands).unwrap_or_else(|e| panic!("{e}"));
    write_if_changed(Path::new(ISOLATION_FILE), &updated);

    let leaked: &'static [&'static str] = Box::leak(
        commands
            .into_iter()
            .map(|c| &*Box::leak(c.into_boxed_str()))
            .collect::<Vec<&'static str>>()
            .into_boxed_slice(),
    );
    let attrs = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(leaked));
    if let Err(e) = tauri_build::try_build(attrs) {
        panic!("tauri-build failed: {e:#}");
    }
}
