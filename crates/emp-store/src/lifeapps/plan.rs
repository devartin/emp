//! Plan generation (pure): which templates a set of answers produces, and the `GenerationPlan` / `PlanDiff` DTOs
//! of §11.3 that the wizard renders ("What we'll create", opt-out switches, "Review & create" counts).

use std::collections::{BTreeMap, BTreeSet};

use chrono::NaiveDate;
use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};

use crate::Result;
use crate::lifeapps::answers::{self, AnswerContext, Mode, Resolved};
use crate::lifeapps::build::{self, Build, BuildCtx};
use crate::lifeapps::manifest::{LifeAppManifest, TemplateKind, TemplateSpec};

/// One item of a plan (`GenerationPlan.items[]`).
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanItem {
    /// Template key.
    pub key: String,
    /// `page|database|view|dashboard|reminder|recurring|sheet|rule|goal`.
    pub kind: String,
    /// Title.
    pub title: String,
    /// Parent template key.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_key: Option<String>,
    /// Can be switched off.
    pub optional: bool,
    /// Switched on.
    pub enabled: bool,
    /// Rows / reminders generated by the item.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub count: Option<u32>,
}

/// A recommendation shown in the wizard.
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanRecommendation {
    /// Step id.
    pub step_id: String,
    /// Value.
    pub value: Value,
    /// Rationale.
    pub why: String,
    /// Source type.
    pub source: String,
}

/// `GenerationPlan` (§11.3).
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerationPlan {
    /// Items in manifest order (disabled optional items included with `enabled:false`).
    pub items: Vec<PlanItem>,
    /// Counts of enabled items by kind (reminders count every generated reminder).
    pub counts: BTreeMap<String, u32>,
    /// Recommendations.
    pub recommendations: Vec<PlanRecommendation>,
    /// Warnings.
    pub warnings: Vec<String>,
}

/// `PlanDiff.update[]`.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanUpdate {
    /// Record key.
    pub key: String,
    /// Changed fields.
    pub fields: Vec<String>,
    /// The user changed one of these fields since it was generated.
    pub conflict: bool,
}

/// `PlanDiff` (§11.3).
#[derive(Clone, Debug, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PlanDiff {
    /// Items that would be created.
    pub add: Vec<PlanItem>,
    /// Records that would change.
    pub update: Vec<PlanUpdate>,
    /// Records left as they are.
    pub keep: Vec<String>,
}

/// The selection of templates for a set of answers.
#[derive(Clone, Debug)]
pub struct Selection {
    /// Resolved answers.
    pub resolved: Resolved,
    /// Enabled template keys.
    pub enabled: BTreeSet<String>,
    /// Items in manifest order.
    pub items: Vec<PlanItem>,
    /// Warnings.
    pub warnings: Vec<String>,
}

fn plan_kind(kind: TemplateKind, spec: &TemplateSpec) -> Option<String> {
    Some(
        match kind {
            TemplateKind::Page => "page",
            TemplateKind::Dashboard => "dashboard",
            TemplateKind::Database => "database",
            TemplateKind::View => "view",
            TemplateKind::Workbook => "sheet",
            TemplateKind::Reminder => "reminder",
            TemplateKind::Recurring => "recurring",
            TemplateKind::Rule => "rule",
            TemplateKind::Row => match spec {
                TemplateSpec::Rows(r) => return r.plan_kind.clone(),
                _ => return None,
            },
        }
        .to_owned(),
    )
}

/// Selects templates: `when` must hold, optional templates in `disabled_keys` are off, and children of disabled
/// pages (and views / rows of disabled databases) are off.
pub fn select(
    m: &LifeAppManifest,
    user: &Map<String, Value>,
    mode: Mode,
    disabled_keys: &[String],
    today: NaiveDate,
    pack: Option<&Value>,
) -> Result<Selection> {
    let resolved = answers::resolve(m, user, mode, today)?;
    let mut ctx = AnswerContext::new(&resolved.answers, today);
    ctx.pack = pack.cloned();
    let disabled: BTreeSet<&str> = disabled_keys.iter().map(String::as_str).collect();
    let mut enabled = BTreeSet::new();
    let mut items = Vec::new();
    let mut warnings = Vec::new();
    for t in &m.templates {
        if !answers::test(t.when.as_deref(), &ctx) {
            continue;
        }
        let spec = t.typed()?;
        let parent_on = t.parent_key.as_ref().is_none_or(|p| enabled.contains(p));
        let target_on = match &spec {
            TemplateSpec::View(v) => enabled.contains(&v.db),
            TemplateSpec::Rows(r) => enabled.contains(&r.db),
            _ => true,
        };
        let mut on = parent_on && target_on;
        if disabled.contains(t.key.as_str()) {
            if t.optional {
                on = false;
            } else {
                warnings.push(format!("{} is required and stays on.", t.title()?));
            }
        }
        if on {
            enabled.insert(t.key.clone());
        }
        if let Some(kind) = plan_kind(t.kind, &spec) {
            items.push(PlanItem {
                key: t.key.clone(),
                kind,
                title: t.title()?,
                parent_key: t.parent_key.clone(),
                optional: t.optional,
                enabled: on,
                count: None,
            });
        }
    }
    for k in &disabled {
        if m.template(k).is_none() {
            warnings.push(format!("Unknown item {k} was ignored."));
        }
    }
    Ok(Selection {
        resolved,
        enabled,
        items,
        warnings,
    })
}

/// Builds the preview plan: selection plus counts from a dry-run build.
pub fn preview(sel: &Selection, b: &Build) -> GenerationPlan {
    let mut items = sel.items.clone();
    for it in &mut items {
        if !it.enabled {
            continue;
        }
        let n = b.count_for(&it.key);
        if n > 0
            && it.kind != "page"
            && it.kind != "dashboard"
            && it.kind != "view"
            && it.kind != "sheet"
        {
            it.count = Some(n);
        }
    }
    let mut counts: BTreeMap<String, u32> = BTreeMap::new();
    for it in items.iter().filter(|i| i.enabled) {
        let add = match it.kind.as_str() {
            "reminder" | "recurring" | "goal" | "rule" => it.count.unwrap_or(0),
            _ => 1,
        };
        if add > 0 {
            *counts.entry(it.kind.clone()).or_default() += add;
        }
    }
    let mut warnings = sel.warnings.clone();
    warnings.extend(b.warnings.iter().cloned());
    GenerationPlan {
        items,
        counts,
        recommendations: sel
            .resolved
            .recommendations
            .iter()
            .map(|(id, r)| PlanRecommendation {
                step_id: id.clone(),
                value: r.value.clone(),
                why: r.why.clone(),
                source: r.source.clone(),
            })
            .collect(),
        warnings,
    }
}

/// Selection + dry-run build + preview (used by `lifeapp_preview`).
pub fn plan(
    m: &LifeAppManifest,
    user: &Map<String, Value>,
    mode: Mode,
    disabled_keys: &[String],
    cx: &BuildCtx,
) -> Result<GenerationPlan> {
    let sel = select(m, user, mode, disabled_keys, cx.today(), cx.pack.as_ref())?;
    let b = build::build(m, &sel, cx)?;
    Ok(preview(&sel, &b))
}
